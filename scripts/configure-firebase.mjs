import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { parseEnv } from 'node:util';

const localEnvPath = new URL('../.env.local', import.meta.url);
const localEnv = existsSync(localEnvPath) ? parseEnv(readFileSync(localEnvPath, 'utf8')) : {};
const key = (process.env.FIREBASE_API_KEY ?? localEnv.FIREBASE_API_KEY ?? '').trim();

if (!/^AIza[0-9A-Za-z_-]{35}$/.test(key)) {
  console.error('Set FIREBASE_API_KEY in .env.local or your build environment before running the app.');
  process.exit(1);
}

const outputPath = fileURLToPath(new URL('../src/environments/firebase-key.local.ts', import.meta.url));
const source = `// Generated by scripts/configure-firebase.mjs. Never commit this file.\nexport const firebaseApiKey = ${JSON.stringify(key)};\n`;
if (!existsSync(outputPath) || readFileSync(outputPath, 'utf8') !== source) {
  writeFileSync(outputPath, source, { mode: 0o600 });
}
console.log('Firebase local configuration prepared.');
